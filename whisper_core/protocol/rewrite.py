"""feature/output-formats — AI-переформатування надиктованого тексту.

Той самий локальний sidecar/бекенд, що AI-протокол (generate.py) і Q&A (qa.py) —
інший лише промт: користувач надиктував чернетку, а модель переписує її під обраний
шаблон (лист / список задач / офіційний рапорт / стисло) або під власний промт.

Межа модуля: БЕЗ Qt і БЕЗ мережі. Виклик LLM інжектиться (`generate_fn`) — у проді це
sidecar.generate із прив'язаним model_path, у тестах фейк. Тож увесь конвеєр
(вибір шаблону → промт → виклик → постобробка) покрито юнітами без важкої моделі.

is_valid_protocol сюди НЕ застосовний (вихід вільний, це не структурований
протокол). Гейт «тихої заглушки» — на боці service.RewriteGenerator: ловимо
FAKE_BACKEND_MARKER і порожнечу, щоб без бекенда показати «встановіть компонент»,
а не заглушку (урок судді).
"""
from __future__ import annotations

from . import generate as _gen

# --- шаблони-промти українською --------------------------------------------
# id → (людська назва-ключ i18n, системний промт). Промти інструктують модель
# ЛИШЕ переписати наданий текст, нічого не вигадуючи понад сказане.

_LETTER = """Ти редактор. Перепиши надиктований чернетковий текст як ввічливого
електронного листа: доречне звертання, зв'язні абзаци, ввічливе завершення.
Не додавай фактів, яких немає в чернетці. Пиши українською. Поверни ЛИШЕ текст
листа, без пояснень."""

_TASKLIST = """Ти помічник-секретар. Переформатуй надиктований текст на чіткий
список задач. Кожна задача — окремим пунктом «- », дієслівним формулюванням.
Використовуй ЛИШЕ те, що є в тексті; нічого не вигадуй. Пиши українською.
Поверни ЛИШЕ список, без пояснень."""

_REPORT = """Ти штабний писар. Перепиши надиктований текст як офіційний рапорт:
діловий стиль, третя особа де доречно, чітка структура. Не додавай фактів понад
сказане. Пиши українською. Поверни ЛИШЕ текст рапорту, без пояснень."""

_CONCISE = """Ти редактор. Стисни надиктований текст до кількох речень, зберігши
всі ключові факти й прибравши повтори та воду. Нічого не додавай понад сказане.
Пиши українською. Поверни ЛИШЕ стислий текст, без пояснень."""

TEMPLATES = {
    "letter": _LETTER,
    "tasklist": _TASKLIST,
    "report": _REPORT,
    "concise": _CONCISE,
}

#: порядок шаблонів для UI (випадний список)
TEMPLATE_IDS = ("letter", "tasklist", "report", "concise")


class UnknownTemplate(ValueError):
    """Невідомий id шаблону (і не передано власного промту)."""


def system_prompt(template_id: str, custom_prompt: "str | None" = None) -> str:
    """Системний промт для режиму. Власний промт користувача (непорожній) має
    пріоритет над вбудованим шаблоном. Порожній id без власного промту → помилка."""
    if custom_prompt and custom_prompt.strip():
        return custom_prompt.strip()
    try:
        return TEMPLATES[template_id]
    except KeyError:
        raise UnknownTemplate(template_id) from None


def build_rewrite_prompt(template_id: str, text: str,
                         custom_prompt: "str | None" = None) -> str:
    """Системний промт шаблону + надиктований текст. Кидає UnknownTemplate, якщо
    id невідомий і власного промту нема."""
    sys = system_prompt(template_id, custom_prompt)
    return (
        f"{sys}\n\n"
        f"=== Надиктований текст ===\n{text}\n\n"
        f"=== Переписаний текст ===\n")


def rewrite_text(text: str, template_id: str, generate_fn, *,
                 custom_prompt: "str | None" = None, max_tokens: int = 1024) -> str:
    """Головна точка входу: чернетка + шаблон → переписаний текст.

    generate_fn(prompt, max_tokens=...) -> str — інжектований виклик LLM (у проді
    sidecar.generate). Порожній вхідний текст → порожній рядок (UI не викликає з
    таким). Кидає UnknownTemplate для невідомого шаблону без власного промту."""
    text = (text or "").strip()
    if not text:
        return ""
    prompt = build_rewrite_prompt(template_id, text, custom_prompt)
    raw = generate_fn(prompt, max_tokens=max_tokens)
    return _gen.postprocess(raw)
