"""feature/voice-edit-selection — Command Mode: голосове редагування виділеного.

Користувач виділив текст (у редакторі транскрипту Балачок АБО в довільному
застосунку), продиктував КОМАНДУ («зроби офіційніше», «переклади англійською»,
«скороти вдвічі», «виправ помилки») — локальна LLM переписує виділене за цією
командою, а результат заміняє виділення (через огляд-перед-дією).

Той самий локальний sidecar/бекенд, що AI-протокол (generate.py), Q&A (qa.py) і
переформатування (rewrite.py у feature/output-formats) — інший лише промт: тут
модель дістає ДВА входи (виділений текст + вільну команду користувача) і має
переписати ПЕРШИЙ за ДРУГИМ, нічого не вигадуючи понад сказане.

Межа модуля: БЕЗ Qt і БЕЗ мережі. Виклик LLM інжектиться (`generate_fn`) — у проді
це sidecar.generate із прив'язаним model_path, у тестах фейк. Тож увесь конвеєр
(команда + текст → промт → виклик → постобробка) покрито юнітами без важкої моделі.

is_valid_protocol сюди НЕ застосовний (вихід вільний, це не структурований
протокол). Гейт «тихої заглушки» — на боці service.CommandEditGenerator: ловимо
FAKE_BACKEND_MARKER і порожнечу, щоб без бекенда показати «встановіть компонент»,
а не заглушку (урок рецензента feature/output-formats).
"""
from __future__ import annotations

from . import generate as _gen

# Системний промт українською. Модель — редактор, що ЛИШЕ виконує команду над
# наданим текстом, нічого не додаючи понад сказане й не пояснюючи себе. Мова
# виводу НЕ нав'язується жорстко: команда може бути «переклади англійською», тож
# правило — виконати саме команду й повернути ЛИШЕ переписаний текст.
_SYSTEM = """Ти уважний редактор тексту. Тобі дають ФРАГМЕНТ тексту й КОМАНДУ, що
з ним зробити (наприклад: зробити офіційнішим, скоротити, виправити помилки,
перекласти, оформити списком). Виконай РІВНО те, що просить команда.

Правила:
- Працюй ЛИШЕ з наданим фрагментом. Не додавай нових фактів, яких у ньому немає.
- Не пояснюй свої дії й не став коментарів — поверни ТІЛЬКИ готовий переписаний
  текст.
- Якщо команда не змінює мову — зберігай мову оригіналу."""


def build_command_prompt(selected_text: str, command: str) -> str:
    """Системний промт + виділений фрагмент + команда користувача → повний промт.

    Обидва входи вважаються непорожніми (виклик робить точка входу apply_command,
    яка й гейтить порожнечу)."""
    return (
        f"{_SYSTEM}\n\n"
        f"=== Команда ===\n{command}\n\n"
        f"=== Фрагмент тексту ===\n{selected_text}\n\n"
        f"=== Переписаний фрагмент ===\n")


def apply_command(selected_text: str, command: str, generate_fn, *,
                  max_tokens: int = 1024) -> str:
    """Головна точка входу: виділений текст + голосова команда → переписаний текст.

    generate_fn(prompt, max_tokens=...) -> str — інжектований виклик LLM (у проді
    sidecar.generate). Порожній виділений текст АБО порожня команда → порожній
    рядок (нема чого/за чим переписувати; UI не викликає з таким)."""
    selected_text = (selected_text or "").strip()
    command = (command or "").strip()
    if not selected_text or not command:
        return ""
    prompt = build_command_prompt(selected_text, command)
    raw = generate_fn(prompt, max_tokens=max_tokens)
    return _gen.postprocess(raw)
