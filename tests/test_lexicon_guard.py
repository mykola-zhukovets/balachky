"""Вартовий лексики: заборонені слова/вирази у видимих UK-рядках i18n.

Борг процесу (Микола, 30-31.07.2026): разова мовна ревізія не тримається —
слово "одруки" повернулося в НОВОМУ ключі з іншої гілки вже ПІСЛЯ того, як
його вичистили. Потрібен тест, а не пам'ять людини: щоразу, коли заборонене
слово знову проникає в STRINGS["uk"], гейт має падати з поясненням, чим його
замінити і чому воно заборонене — без пошуку по історії чату чи по Vault.

Джерело правил: внутрішній словник лексики команди — розділ 2.2 (кальки),
2.3 (канцеляризми), 3 (живий розділ правок власника). Кожне правило нижче —
окремий рядок цього словника; при новій правці власника спершу дописують
рядок у словник, потім тут.

Тест бере лише ЗНАЧЕННЯ STRINGS["uk"] (видимі рядки), не ключі й не коментарі
коду — так само, як test_i18n_canon.py.
"""
import re
import unittest

from fronts.desktop.i18n import STRINGS

UK = STRINGS["uk"]

# --------------------------------------------------------------------------
# Правила: (id, regex, заміна, причина, виняткові ключі з поясненням)
#
# regex зумисно вузький (word-boundary / точний стем), щоб не зачепити
# споріднені легальні слова — де це важливо, коментар пояснює межу.
# --------------------------------------------------------------------------

RULES = [
    dict(
        id="одруки",
        # одрук/одруки/одруком/одруку… — стем "одрук" не перетинається з
        # жодним легальним українським словом (на відміну від голого "друк",
        # яке лишається в "друкар", "надрукувати" тощо — його НЕ чіпаємо).
        pattern=re.compile(r"одрук[а-яіїєґ']*", re.IGNORECASE),
        replacement="помилка(и) в словах / написанні",
        reason=(
            "новотвору «одруки» немає в академічних словниках української; "
            "до того ж людина диктує голосом, а не друкує — «друкарська "
            "помилка» тут навіть не за адресою (Vault СЛОВНИК-лексики, "
            "правка 2026-07-30)"
        ),
    ),
    dict(
        id="тапи",
        # \bтап[иі]?\b — лише "тап"/"тапи"/"тапі" як окреме слово; НЕ чіпає
        # "тапки", "тапка" (взуття) чи будь-яке слово, де за "тап" іде інша
        # літера.
        pattern=re.compile(r"\bтап[иі]?\b", re.IGNORECASE),
        replacement="натискання",
        reason="жаргон з мобільних інтерфейсів, у Балачках керують мишею/клавіатурою",
    ),
    dict(
        id="chystka_fileriv",
        pattern=re.compile(r"чистк\w*\s+філер\w*", re.IGNORECASE),
        replacement="вилучення слів-паразитів",
        reason="канцелярський жаргон розробника, не мова користувача",
    ),
    dict(
        id="symlink",
        pattern=re.compile(r"симлінк\w*", re.IGNORECASE),
        replacement="ярлик (посилання)",
        reason="технічний unix-термін незрозумілий звичайному користувачеві Windows",
    ),
    dict(
        id="transkrypt",
        pattern=re.compile(r"транскрипт\w*", re.IGNORECASE),
        replacement="розшифровка / розшифрування",
        reason=(
            "одне поняття мусить називатися однаково скрізь в UI (Vault "
            "СЛОВНИК-лексики, правка 2026-07-30); на момент запису вартового "
            "легальних ужитків «транскрипт» у STRINGS[\"uk\"] не знайдено"
        ),
    ),
    dict(
        id="spiker",
        pattern=re.compile(r"спікер\w*", re.IGNORECASE),
        replacement="учасник (співрозмовник)",
        reason="термінологічна єдність з «нарада» (не «зустріч», не «мітинг»)",
    ),
    dict(
        id="pryjnyaty_uchast",
        # калька "приймати/прийняти участь" — дозволяємо будь-яку словоформу
        # дієслова між "прийн…" та "участь".
        pattern=re.compile(r"прийн\w*\s+участь", re.IGNORECASE),
        replacement="брати / взяти участь",
        reason="калька з російської (Vault СЛОВНИК-лексики, §2.2)",
    ),
    dict(
        id="u_vypadku_yakscho",
        pattern=re.compile(r"у випадку,?\s+якщо", re.IGNORECASE),
        replacement="якщо",
        reason="канцелярська калька (Vault СЛОВНИК-лексики, §2.2)",
    ),
]

# --------------------------------------------------------------------------
# "Ти"-форми наказового способу: стандарт проєкту — звертання на "Ви"
# (Vault СЛОВНИК-лексики, правка 2026-07-30: 22 ключі виправлено).
# Перевіряємо лише ГОЛЕ "ти"-дієслово як окреме слово — форма на "Ви"
# («виберіть», «перевірте», «натисніть»…) регексом не зачіпається, бо
# закінчується інакше.
# --------------------------------------------------------------------------

_TY_IMPERATIVES = ["вибери", "введи", "збережи", "натисни", "перевір", "виправ"]

# cmdedit_intro наводить ПРИКЛАДИ команд, які користувач сам продиктує
# програмі ("зроби офіційніше", "виправ помилки") — це цитата чужого
# мовлення, а не звертання UI до користувача на "ти". Легальний виняток.
_TY_IMPERATIVE_EXCEPTIONS = frozenset({"cmdedit_intro"})

for _verb in _TY_IMPERATIVES:
    RULES.append(dict(
        id=f"ty_forma_{_verb}",
        pattern=re.compile(rf"\b{_verb}\b", re.IGNORECASE),
        replacement=f"{_verb[:-1]}ть (форма на «Ви»)",
        reason="звертання в UI Балачок — на «Ви», не на «ти» (Vault СЛОВНИК-лексики, правка 2026-07-30)",
        exceptions=_TY_IMPERATIVE_EXCEPTIONS,
    ))


class LexiconGuard(unittest.TestCase):
    """Кожне правило перевіряється через subTest, щоб повідомлення падіння
    точково називало ключ, заборонене слово, заміну й причину."""

    def _check_rule(self, rule):
        exceptions = rule.get("exceptions", frozenset())
        hits = []
        for key, value in UK.items():
            if key in exceptions:
                continue
            m = rule["pattern"].search(str(value))
            if m:
                hits.append((key, m.group(0)))
        if hits:
            lines = "\n".join(f"  ключ={k!r} слово={w!r}" for k, w in hits)
            self.fail(
                f"[{rule['id']}] заборонене слово знайдено:\n{lines}\n"
                f"Замінити на: {rule['replacement']}\n"
                f"Причина: {rule['reason']}"
            )

    def test_lexicon_rules(self):
        for rule in RULES:
            with self.subTest(rule=rule["id"]):
                self._check_rule(rule)


if __name__ == "__main__":
    unittest.main()
