"""Проста dict-based локалізація UI (UK/EN). Застосування — після перезапуску.

Механізм: одна глобальна мова `_LANG` (виставляється на старті з cfg.ui_language,
ДО побудови вікна). `tr(key, **kw)` бере рядок за стабільним snake_case-ключем із
поточної мови, фолбек — на 'uk', потім на сам ключ; `.format(**kw)` лише коли є
іменовані плейсхолдери (kw). `plural(n, uk, en)` дає коректну словоформу.

ВАЖЛИВО: коди станів (напр. FileStatus у main_window) порівнюються в коді —
НЕ порівнюй перекладений текст бейджів/статусів. tr — лише для показу.
"""

_LANG = "uk"

from whisper_core.offline_package import OFFLINE_IMPORT_BUTTON_TEXT_UK


def set_language(code: str) -> None:
    """Виставити мову UI. Невідомий код → 'uk'. Кличеться на старті до вікна."""
    global _LANG
    _LANG = code if code in STRINGS else "uk"


def current_language() -> str:
    return _LANG


def tr(msgid: str, **kw) -> str:
    """Рядок за ключем поточної мови; фолбек uk → сам ключ. format лише з kw.
    Перший параметр — msgid (НЕ 'key'), щоб рядки з {key}-плейсхолдером можна
    було форматувати як tr('...', key=...) без зіткнення імен параметрів."""
    s = STRINGS.get(_LANG, {}).get(msgid)
    if s is None:
        s = STRINGS["uk"].get(msgid, msgid)
    if kw:
        try:
            s = s.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass                     # безпечно: краще сирий рядок, ніж крах
    # Токен %%ACCENT%% у inline-стилях посилань → живий колір активної теми
    # (золото вдень / світло-червоне вночі). Інакше hex був би вшитий у рядок і
    # світився б денним у нічному режимі. Ліниво: theme імпортуємо лише за потреби.
    if "%%ACCENT%%" in s:
        from . import theme
        s = s.replace("%%ACCENT%%", theme.GOLD_EYEBROW)
    return s


def plural(n: int, uk, en):
    """Словоформа (без числа). uk=(one, few, many); en=(one, other).
    Укр.: 1 слово / 2-4 слова / 5+ слів. Англ.: 1 word / N words."""
    if _LANG == "en":
        one, other = en
        return one if n == 1 else other
    one, few, many = uk
    if n % 100 in (11, 12, 13, 14):
        return many
    r = n % 10
    if r == 1:
        return one
    if r in (2, 3, 4):
        return few
    return many


def human_size(nbytes: int) -> str:
    """Форматування розміру файлу/пам'яті з урахуванням мови UI.
    Для uk десятковий роздільник — кома (18,1 ГБ), для en — крапка (18.1 GB).
    Одиниці через tr('unit_gb') / tr('unit_mb').
    """
    nbytes = nbytes or 0
    gb = nbytes / (1024 ** 3)
    if gb >= 1:
        val_str = f"{gb:.1f}"
        unit = tr("unit_gb")
    else:
        mb = nbytes / (1024 ** 2)
        val_str = f"{mb:.0f}"
        unit = tr("unit_mb")

    if current_language() == "uk":
        val_str = val_str.replace(".", ",")

    return f"{val_str} {unit}"


def format_decimal(value: float, decimals: int = 1) -> str:
    """Число з фіксованою кількістю знаків після коми: кома-роздільник у uk,
    крапка в en. Для метрик поза human_size (відсоток поступу, швидкість
    завантаження в МБ/с)."""
    s = f"{value:.{decimals}f}"
    if current_language() == "uk":
        s = s.replace(".", ",")
    return s


def format_duration(seconds: "int | float") -> str:
    """Компактна тривалість «5 хв 55 с» (uk) / «5 min 55 s» (en). Без хвилин,
    якщо лишилось менше хвилини. Використовується лише коли час РАХОВАНИЙ
    (є total і виміряна швидкість) — ніколи не вигадується."""
    total_seconds = max(0, int(seconds))
    minutes, secs = divmod(total_seconds, 60)
    if current_language() == "uk":
        return f"{minutes} хв {secs} с" if minutes else f"{secs} с"
    return f"{minutes} min {secs} s" if minutes else f"{secs} s"


